type Translate = (text: string, values?: Record<string, string | number>) => string
const LanguageContext = createContext<{ language: Language; locale: string; t: Translate; toggle: () => void }>({ language: 'uk', locale: 'uk-UA', t: text => text, toggle: () => {} })

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>('uk')
  useEffect(() => {
    const saved = localStorage.getItem('lager-language')
    if (saved === 'uk' || saved === 'ru') setLanguage(saved)
  }, [])
  useEffect(() => { document.documentElement.lang = language }, [language])
  const value = useMemo(() => {
    const t: Translate = (text, values = {}) => {
      let translated = language === 'ru' ? ru[text] || text : text
      for (const [key, value] of Object.entries(values)) translated = translated.replaceAll(`{${key}}`, String(value))
      return translated
    }
    return {
      language,
      locale: language === 'ru' ? 'ru-RU' : 'uk-UA',
      t,
      toggle: () => setLanguage(current => {
        const next = current === 'uk' ? 'ru' : 'uk'
        localStorage.setItem('lager-language', next)
        return next
      }),
    }
  }, [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export const useLanguage = () => useContext(LanguageContext)

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { language, toggle } = useLanguage()
  return <Button type="button" size={compact ? 'sm' : 'default'} variant="outline" onClick={toggle} aria-label={language === 'uk' ? 'Переключить на русский' : 'Перемкнути на українську'}>
    <Languages size={15} /> {language === 'uk' ? 'RU' : 'UA'}
  </Button>
}
